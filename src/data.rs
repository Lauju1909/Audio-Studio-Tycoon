pub fn get_available_platforms(year: u32) -> Vec<&'static PlatformSpec> {
    let mut list: Vec<&'static PlatformSpec> = PLATFORMS
        .iter()
        .filter(|p| year >= p.unlock_year && year <= p.end_year)
        .collect();
    if list.is_empty() {
        // Fallback so the player never has 0 platforms
        list.push(&PLATFORMS[PLATFORMS.len() - 1]);
    }
    list
}

/// Returns all platforms whose unlock year matches `year`.
pub fn get_newly_unlocked_platforms(year: u32) -> Vec<&'static PlatformSpec> {
    PLATFORMS.iter().filter(|p| p.unlock_year == year).collect()
}

/// Returns all platforms that retired after `year - 1` (i.e. `p.end_year + 1 == year`).
pub fn get_newly_retired_platforms(year: u32) -> Vec<&'static PlatformSpec> {
    PLATFORMS
        .iter()
        .filter(|p| p.end_year.checked_add(1) == Some(year))
        .collect()
}

/// Returns `true` if the named standard platform is active in `year`.
pub fn is_platform_active(name: &str, year: u32) -> bool {
    PLATFORMS
        .iter()
        .any(|p| p.name == name && year >= p.unlock_year && year <= p.end_year)
}

