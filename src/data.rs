pub fn get_year_event(year: u32) -> YearEventSpec {
    if (START_YEAR..=2026).contains(&year) {
        return HISTORICAL_YEAR_EVENTS[(year - START_YEAR) as usize].clone();
    }
    let (topics, genres): (&[&str], &[&str]) = if year < START_YEAR {
        (START_TOPICS, START_GENRES)
    } else {
        (START_TOPICS, GENRES)
    };
    let t = topics[(year as usize) % topics.len()];
    let g = genres[(year as usize * 3) % genres.len()];
    YearEventSpec {
        year,
        title_de: "Neues Geschäftsjahr & Markttrend-Wechsel",
        title_en: "New Fiscal Year & Market Trend Shift",
        desc_de: "Die Hörerschaft und Spieler suchen nach frischen Ideen im neuen Jahr.",
        desc_en: "Listeners and players are looking for fresh ideas in the new year.",
        trend_topic: Some(t),
        trend_genre: Some(g),
        sales_multi_delta: 0.02,
        cash_grant: 0,
        hype_bonus: 5.0,
    }
}
