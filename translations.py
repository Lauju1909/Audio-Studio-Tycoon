"""
Translations for Audio Studio Tycoon.
Only German is stored, other languages are translated on-the-fly.
"""
import sys
import os
import json
import urllib.request
import urllib.parse
import re
import threading

CACHE_FILE = "translation_cache.json"
_TRANSLATION_CACHE = {}
TRANSLATIONS_UPDATED = False
PENDING_TRANSLATIONS = 0
CACHE_LOCK = threading.Lock()

if os.path.exists(CACHE_FILE):
    try:
        with open(CACHE_FILE, "r", encoding="utf-8") as cf:
            _TRANSLATION_CACHE = json.load(cf)
    except:
        pass

def save_cache():
    try:
        with CACHE_LOCK:
            with open(CACHE_FILE, "w", encoding="utf-8") as cf:
                json.dump(_TRANSLATION_CACHE, cf, ensure_ascii=False, indent=2)
    except:
        pass

def background_translate(text, target_lang, cache_key, source_lang="de"):
    global PENDING_TRANSLATIONS, TRANSLATIONS_UPDATED
    try:
        placeholders = {}
        def replacer(match):
            ph = match.group(1)
            token = f"__PH_{len(placeholders)}__"
            placeholders[token] = ph
            return token
        protected_text = re.sub(r"\{([^}]+)\}", replacer, text)
        encoded_text = urllib.parse.quote(protected_text)
        url = f"https://translate.googleapis.com/translate_a/single?client=gtx&sl={source_lang}&tl={target_lang}&dt=t&q={encoded_text}"
        
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=5) as response:
            result = json.loads(response.read().decode("utf-8"))
            translated = "".join([sentence[0] for sentence in result[0]])
            for token, ph in placeholders.items():
                token_pattern = re.compile(token.replace("_", r"_?\s*"))
                translated = token_pattern.sub(f"{{{ph}}}", translated)
            
            with CACHE_LOCK:
                _TRANSLATION_CACHE[cache_key] = translated
            save_cache()
            
            TRANSLATIONS_UPDATED = True
    except Exception as e:
        pass
    finally:
        PENDING_TRANSLATIONS -= 1

def get_system_language():
    try:
        if sys.platform == "win32":
            import ctypes
            windll = ctypes.windll.kernel32
            lang_id = windll.GetUserDefaultUILanguage()
            primary_lang = lang_id & 0x3ff
            if primary_lang == 0x07:
                return "de"
        return "en"
    except:
        return "en"

CURRENT_LANGUAGE = get_system_language()

def set_language(lang):
    global CURRENT_LANGUAGE
    CURRENT_LANGUAGE = lang

def get_text(text_key, **kwargs):
    """
    Retrieves the translated text for a given key.
    Prioritizes: CURRENT_LANGUAGE -> Cache -> English (en) -> German (de) -> Key itself.
    Triggers background translation for missing strings.
    """
    global PENDING_TRANSLATIONS
    
    # 1. Try current language static translation
    text = TRANSLATIONS.get(CURRENT_LANGUAGE, {}).get(text_key)
    
    # 2. Try cache
    cache_key = f"{CURRENT_LANGUAGE}_{text_key}"
    if text is None and cache_key in _TRANSLATION_CACHE:
        text = _TRANSLATION_CACHE[cache_key]

    # 3. If still not found, we need a base text to fall back to and translate from
    if text is None:
        base_text = text_key
        source_lang = "en"
        
        if text_key in TRANSLATIONS.get("en", {}):
            base_text = TRANSLATIONS["en"][text_key]
            source_lang = "en"
        elif text_key in TRANSLATIONS.get("de", {}):
            base_text = TRANSLATIONS["de"][text_key]
            source_lang = "de"
            
        text = base_text
        
        # Trigger background translation
        if cache_key not in _TRANSLATION_CACHE:
            # Set temporary value to prevent spamming requests
            _TRANSLATION_CACHE[cache_key] = base_text
            PENDING_TRANSLATIONS += 1
            threading.Thread(
                target=background_translate, 
                args=(base_text, CURRENT_LANGUAGE, cache_key, source_lang), 
                daemon=True
            ).start()

    if kwargs:
        try:
            return text.format(**kwargs)
        except:
            return text
    return text

