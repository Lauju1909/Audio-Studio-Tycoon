import json
import sys
import os
sys.path.append('c:\\Users\\lauri\\.gemini\\antigravity\\scratch\\Audio_Studio_Tycoon')
import translations

with open('c:\\Users\\lauri\\.gemini\\antigravity\\scratch\\Audio_Studio_Tycoon\\translations.py', 'w', encoding='utf-8') as f:
    f.write('"""\nTranslations for Audio Studio Tycoon.\nOnly German is stored, other languages are translated on-the-fly.\n"""\n')
    f.write('import sys\nimport os\nimport json\nimport urllib.request\nimport urllib.parse\nimport re\nimport threading\n\n')
    f.write('CACHE_FILE = "translation_cache.json"\n')
    f.write('_TRANSLATION_CACHE = {}\n\n')
    f.write('if os.path.exists(CACHE_FILE):\n')
    f.write('    try:\n        with open(CACHE_FILE, "r", encoding="utf-8") as cf:\n            _TRANSLATION_CACHE = json.load(cf)\n    except:\n        pass\n\n')
    f.write('def save_cache():\n')
    f.write('    try:\n        with open(CACHE_FILE, "w", encoding="utf-8") as cf:\n            json.dump(_TRANSLATION_CACHE, cf, ensure_ascii=False, indent=2)\n    except:\n        pass\n\n')
    
    f.write('def background_translate(text, target_lang, cache_key, source_lang="de"):\n')
    f.write('    placeholders = {}\n')
    f.write('    def replacer(match):\n')
    f.write('        ph = match.group(1)\n')
    f.write('        token = f"__PH_{len(placeholders)}__"\n')
    f.write('        placeholders[token] = ph\n')
    f.write('        return token\n')
    f.write('    protected_text = re.sub(r"\\{([^}]+)\\}", replacer, text)\n')
    f.write('    encoded_text = urllib.parse.quote(protected_text)\n')
    f.write('    url = f"https://translate.googleapis.com/translate_a/single?client=gtx&sl={source_lang}&tl={target_lang}&dt=t&q={encoded_text}"\n')
    f.write('    try:\n')
    f.write('        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})\n')
    f.write('        with urllib.request.urlopen(req, timeout=5) as response:\n')
    f.write('            result = json.loads(response.read().decode("utf-8"))\n')
    f.write('            translated = "".join([sentence[0] for sentence in result[0]])\n')
    f.write('            for token, ph in placeholders.items():\n')
    f.write('                token_pattern = re.compile(token.replace("_", r"_?\\s*"))\n')
    f.write('                translated = token_pattern.sub(f"{{{ph}}}", translated)\n')
    f.write('            _TRANSLATION_CACHE[cache_key] = translated\n')
    f.write('            save_cache()\n')
    f.write('    except Exception:\n')
    f.write('        pass\n\n')

    f.write('def get_system_language():\n')
    f.write('    try:\n')
    f.write('        if sys.platform == "win32":\n')
    f.write('            import ctypes\n')
    f.write('            windll = ctypes.windll.kernel32\n')
    f.write('            lang_id = windll.GetUserDefaultUILanguage()\n')
    f.write('            primary_lang = lang_id & 0x3ff\n')
    f.write('            if primary_lang == 0x07:\n')
    f.write('                return "de"\n')
    f.write('        return "en"\n')
    f.write('    except:\n')
    f.write('        return "en"\n\n')
    f.write('CURRENT_LANGUAGE = get_system_language()\n\n')
    f.write('def set_language(lang):\n')
    f.write('    global CURRENT_LANGUAGE\n')
    f.write('    CURRENT_LANGUAGE = lang\n\n')
    
    f.write('def get_text(text_key, **kwargs):\n')
    f.write('    base_text = TRANSLATIONS.get("de", {}).get(text_key, text_key)\n')
    f.write('    if CURRENT_LANGUAGE == "de":\n')
    f.write('        text = base_text\n')
    f.write('    else:\n')
    f.write('        cache_key = f"{CURRENT_LANGUAGE}_{base_text}"\n')
    f.write('        if cache_key in _TRANSLATION_CACHE:\n')
    f.write('            text = _TRANSLATION_CACHE[cache_key]\n')
    f.write('        else:\n')
    f.write('            _TRANSLATION_CACHE[cache_key] = base_text\n')
    f.write('            threading.Thread(target=background_translate, args=(base_text, CURRENT_LANGUAGE, cache_key), daemon=True).start()\n')
    f.write('            text = base_text\n')
    f.write('    if kwargs:\n')
    f.write('        try:\n')
    f.write('            return text.format(**kwargs)\n')
    f.write('        except:\n')
    f.write('            return text\n')
    f.write('    return text\n\n')

    f.write('TRANSLATIONS = {\n    "de": {\n')
    sorted_keys = sorted(list(translations.TRANSLATIONS["de"].keys()))
    for key in sorted_keys:
        val = str(translations.TRANSLATIONS["de"][key]).replace('"', '\\"').replace('\n', '\\n')
        f.write(f'        "{key}": "{val}",\n')
    f.write('    }\n}\n')
